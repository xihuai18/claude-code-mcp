import { describe, expect, it } from "vitest";
import {
  computeResumeToken,
  getResumeSecret,
  getResumeSecrets,
  isValidResumeToken,
} from "../src/utils/resume-token.js";

describe("resume-token", () => {
  it("computes deterministic token for the same session and secret", () => {
    const one = computeResumeToken("session-1", "secret-1");
    const two = computeResumeToken("session-1", "secret-1");
    expect(one).toBe(two);
  });

  it("accepts token generated by any configured secret (rotation support)", () => {
    const token = computeResumeToken("session-1", "old-secret");
    expect(isValidResumeToken("session-1", token, ["new-secret", "old-secret"])).toBe(true);
  });

  it("rejects invalid token and mismatched lengths", () => {
    const token = computeResumeToken("session-1", "secret-1");
    expect(isValidResumeToken("session-1", `${token}x`, ["secret-1"])).toBe(false);
    expect(isValidResumeToken("session-1", "bad-token", ["secret-1"])).toBe(false);
  });

  it("parses resume secrets from env", () => {
    const original = process.env.CLAUDE_CODE_MCP_RESUME_SECRET;
    try {
      process.env.CLAUDE_CODE_MCP_RESUME_SECRET = "a, b ,,c";
      expect(getResumeSecrets()).toEqual(["a", "b", "c"]);
      expect(getResumeSecret()).toBe("a");
    } finally {
      if (original === undefined) delete process.env.CLAUDE_CODE_MCP_RESUME_SECRET;
      else process.env.CLAUDE_CODE_MCP_RESUME_SECRET = original;
    }
  });
});
